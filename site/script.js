/* YOFENG news manager: static-site/browser-local implementation. Replace the password before use. */
const NEWS_ADMIN_PASSWORD = 'YofengNews@2026';
const NEWS_API_BASE = '/api';
const NEWS_ADMIN_TOKEN_KEY = 'yofeng-news-admin-token-v2';
const CUSTOM_NEWS_LANGS = ['zh-TW', 'zh-CN', 'en', 'ja'];
const CUSTOM_NEWS_LOCALES = {'zh-TW':'zh-TW','zh-CN':'zh-CN','en':'en-US','ja':'ja-JP'};
let customNewsCache = [];

function currentSiteLanguage(){ return document.getElementById('language')?.value || localStorage.getItem('yofeng-lang') || 'zh-TW'; }
function newsUIText(key, fallback){
  const lang = currentSiteLanguage();
  return (typeof translations !== 'undefined' && translations[lang] && translations[lang][key]) || fallback;
}
function safeExternalURL(value){
  if(!value) return '';
  try { const u = new URL(value); return ['http:','https:'].includes(u.protocol) ? u.href : ''; }
  catch(e){ return ''; }
}
function getNewsAdminToken(){ return sessionStorage.getItem(NEWS_ADMIN_TOKEN_KEY) || ''; }
function setNewsAdminToken(token){
  if(token) sessionStorage.setItem(NEWS_ADMIN_TOKEN_KEY, token);
  else sessionStorage.removeItem(NEWS_ADMIN_TOKEN_KEY);
}

function renderCustomNews(lang){
  const target = document.getElementById('customNewsList');
  if(!target) return;
  lang = lang || currentSiteLanguage();
  const items = Array.isArray(customNewsCache) ? [...customNewsCache].sort((a,b) => String(b.date).localeCompare(String(a.date))) : [];
  target.replaceChildren();
  items.forEach(item => {
    const translation = item.translations?.[lang] || item.translations?.['zh-TW'];
    if(!translation) return;
    const article = document.createElement('article');
    article.className = 'news-entry news-entry-custom';
    const content = document.createElement('div');
    content.className = 'news-entry-content news-entry-content-full';
    const date = document.createElement('time');
    date.dateTime = item.date;
    const parsedDate = new Date(item.date + 'T12:00:00');
    date.textContent = Number.isNaN(parsedDate.getTime()) ? item.date : new Intl.DateTimeFormat(CUSTOM_NEWS_LOCALES[lang] || 'zh-TW', {year:'numeric', month:'2-digit', day:'2-digit'}).format(parsedDate);
    const title = document.createElement('h2');
    title.textContent = translation.title || '';
    const body = document.createElement('p');
    body.textContent = translation.body || '';
    content.append(date, title, body);
    const linkURL = safeExternalURL(item.url || '');
    if(linkURL){
      const linkList = document.createElement('div');
      linkList.className = 'news-link-list';
      const link = document.createElement('a');
      link.href = linkURL;
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
      link.textContent = translation.linkLabel || newsUIText('newspage.adminReadMore', 'Read more ↗');
      linkList.append(link);
      content.append(linkList);
    }
    article.append(content);
    target.append(article);
  });
}

async function fetchCustomNews(){
  const target = document.getElementById('customNewsList');
  if(!target) return;
  try{
    const response = await fetch(`${NEWS_API_BASE}/news`, {headers:{'Accept':'application/json'}});
    if(!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    customNewsCache = Array.isArray(data) ? data : [];
    renderCustomNews(currentSiteLanguage());
  }catch(error){
    customNewsCache = [];
    renderCustomNews(currentSiteLanguage());
    console.warn('Unable to load cloud news:', error);
  }
}

async function loginNewsAdmin(password){
  const response = await fetch(`${NEWS_API_BASE}/admin/login`, {
    method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({password})
  });
  let data = {};
  try { data = await response.json(); } catch(e) {}
  if(!response.ok) throw new Error(data.message || 'LOGIN_FAILED');
  if(!data.token) throw new Error('LOGIN_FAILED');
  setNewsAdminToken(data.token);
  return data.token;
}

async function saveNewsToCloud(payload){
  const token = getNewsAdminToken();
  const response = await fetch(`${NEWS_API_BASE}/news`, {
    method:'POST',
    headers:{'Content-Type':'application/json','Authorization':`Bearer ${token}`},
    body:JSON.stringify(payload)
  });
  let data = {};
  try { data = await response.json(); } catch(e) {}
  if(response.status === 401){ setNewsAdminToken(''); throw new Error('UNAUTHORIZED'); }
  if(!response.ok) throw new Error(data.message || 'SAVE_FAILED');
  return data;
}

function initNewsAdmin(){
  const button = document.getElementById('openNewsAdmin');
  const panel = document.getElementById('newsAdminPanel');
  const form = document.getElementById('newsAdminForm');
  const cancel = document.getElementById('cancelNewsAdmin');
  const status = document.getElementById('newsAdminStatus');
  if(!button || !panel || !form || !cancel || !status) return;

  button.addEventListener('click', async () => {
    if(!panel.hidden){ panel.hidden = true; return; }
    let token = getNewsAdminToken();
    if(!token){
      const entered = window.prompt(newsUIText('newspage.adminPasswordPrompt', 'Enter the administrator password:'));
      if(entered === null) return;
      try{
        token = await loginNewsAdmin(entered);
      }catch(error){
        window.alert(newsUIText('newspage.adminBadPassword', 'Incorrect password.'));
        return;
      }
    }
    panel.hidden = false;
    status.hidden = true;
    panel.scrollIntoView({behavior:'smooth', block:'start'});
    form.elements.namedItem('news-date')?.focus();
  });

  cancel.addEventListener('click', () => { panel.hidden = true; form.reset(); status.hidden = true; });

  form.addEventListener('submit', async event => {
    event.preventDefault();
    status.hidden = true;
    const fd = new FormData(form);
    const date = String(fd.get('news-date') || '').trim();
    const urlInput = String(fd.get('news-url') || '').trim();
    const url = urlInput ? safeExternalURL(urlInput) : '';
    if(!date || (urlInput && !url)){
      status.textContent = newsUIText('newspage.adminSaveError', 'Could not save. Please check the date and URL.');
      status.hidden = false;
      return;
    }
    const itemTranslations = {};
    for(const lang of CUSTOM_NEWS_LANGS){
      const title = String(fd.get('title-' + lang) || '').trim();
      const body = String(fd.get('body-' + lang) || '').trim();
      const linkLabel = String(fd.get('linkLabel-' + lang) || '').trim();
      if(!title || !body){
        status.textContent = newsUIText('newspage.adminValidation', 'Please provide a title and content in all four languages.');
        status.hidden = false;
        return;
      }
      itemTranslations[lang] = {title, body, linkLabel};
    }

    const submit = form.querySelector('button[type="submit"]');
    if(submit) submit.disabled = true;
    try{
      await saveNewsToCloud({date, url, translations:itemTranslations});
      await fetchCustomNews();
      form.reset();
      panel.hidden = true;
      window.alert(newsUIText('newspage.adminSaved', 'The news item has been saved and added to the list.'));
    }catch(error){
      if(error.message === 'UNAUTHORIZED'){
        status.textContent = newsUIText('newspage.adminBadPassword', 'Incorrect password.');
      }else{
        status.textContent = newsUIText('newspage.adminSaveError', 'Could not save. Please try again.');
      }
      status.hidden = false;
    }finally{
      if(submit) submit.disabled = false;
    }
  });
}

if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => { initNewsAdmin(); fetchCustomNews(); });
else { initNewsAdmin(); fetchCustomNews(); }
window.__newsAdminReady = true;
