function updateProductDirectoryLanguage(lang){
  if(typeof document==='undefined') return;
  const t=productUITranslations[lang]||productUITranslations['zh-TW'];
  document.querySelectorAll('[data-product-i18n]').forEach(el=>{
    const val=t[el.dataset.productI18n];
    if(val!==undefined) el.textContent=val;
  });
  const search=document.getElementById('productSearch');
  if(search && t['productDirectory.searchPlaceholder']) search.placeholder=t['productDirectory.searchPlaceholder'];
  if(typeof window.refreshProductDirectoryLanguage==='function') window.refreshProductDirectoryLanguage(lang);
}

function setLang(lang){
  const map={ 'zh-TW':'zh-Hant','zh-CN':'zh-Hans','ja':'ja','en':'en' };
  document.documentElement.lang=map[lang]||'zh-Hant';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const val=translations[lang]?.[el.dataset.i18n];
    if(val!==undefined) el.innerText=val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const val=translations[lang]?.[el.dataset.i18nPlaceholder];
    if(val!==undefined) el.placeholder=val;
  });
  localStorage.setItem('yofeng-lang',lang);
  const selector=document.getElementById('language');
  if(selector) selector.value=lang;
  updateProductDirectoryLanguage(lang);
  if(window.__newsAdminReady && typeof renderCustomNews==='function') renderCustomNews(lang);
}

